package Operator;

public class RelationalOperator {

    public static void main(String[]args){

        //Check if 10 is greater than 5
        System.out.println(10>5);

        //Check if 7 is less than or equal to 7
        System.out.println(7<=7);

        //Compare two numbers
        System.out.println(15==15);

        //Check if 25 is not equal to 30
        System.out.println(25!=30);

        //Compare two variable and print which is greater
        int num1 = 3;
        int num2 = 4;

        if(num1 > num2){
            System.out.println("Num1 is greater");
        }
        else{
            System.out.println("Num2 is greater");
        }

        //Check if the number is less than another number
        System.out.println(15<20);

        //Compare 50 and 100 by using <
        System.out.println(50 < 100);

        //Check equality of two integers
        int x = 28;
        int y = 87;
        System.out.println(x==y);




    }
}
