package Operator;

public class AssignmentOperator {
    public static void main(String[]args){

        //Assign value 10 to the variable
        int a = 10;

        //Add 5 to a variable using +=
        a+=5;
        System.out.println(a);

        //Subtract 3 using -=
        a-=3;
        System.out.println(a);

        //Multiply a variable using *=
        a*=2;
        System.out.println(a);

        //Divide a variable using /=
        a/=2;
        System.out.println(a);

        //Find remainder using %=
        a%=5;
        System.out.println(a);

        //Increase value using++
        a++;
        System.out.println(a);

        //Decrease value using --
        a--;
        System.out.println(a);
    }
}
